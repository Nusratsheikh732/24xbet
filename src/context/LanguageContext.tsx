const dictionaries: Record<Language, Dict> = { en, bn };

const STORAGE_KEY = '24xbet_language';

interface LanguageContextValue {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
  bn: (text: string | number) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === 'en' ? 'en' : 'bn';
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const setLanguage = (lang: Language) => setLanguageState(lang);

  const t = (key: string): string => {
    return dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  };

  const bnNums = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
  const bn = (text: string | number): string => {
    if (language !== 'bn') return String(text);
    return String(text).replace(/[0-9]/g, (d) => bnNums[parseInt(d)]);
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, bn }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
}
